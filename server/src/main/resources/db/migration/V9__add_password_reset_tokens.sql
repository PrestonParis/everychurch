-- Forgot/reset password (scaffolding pass, docs/PROMPTS.md 2026-09-22 — no client UI or
-- server support existed for this at all; the project owner's own login flow was
-- untested and it was "safe to assume there's no forgotten password feature").
--
-- Only a SHA-256 hash of the token is stored, never the raw value — the raw token
-- exists only in the emailed link, the same reasoning as never storing a plaintext
-- password (see users.password_hash / AuthService).
CREATE TABLE password_reset_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id),
    token_hash character varying(64) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    expires_at timestamp(6) with time zone NOT NULL,
    used_at timestamp(6) with time zone,
    CONSTRAINT uq_password_reset_tokens_token_hash UNIQUE (token_hash)
);

-- AuthService looks tokens up by hash on every reset attempt, and clears a user's
-- outstanding tokens whenever a new one is issued.
CREATE INDEX idx_password_reset_tokens_user_id ON password_reset_tokens (user_id);
