-- "Favorite a church" (project-owner audit, 2026-09-22) — purely personal, unlike
-- Member (congregational, visible to the whole church) or ChurchStaff (administrative):
-- nobody but the favoriting user ever sees this row. Same shape as members/church_staff
-- otherwise — one row per (church, user), unique so favoriting twice is a no-op/409
-- rather than a duplicate.
CREATE TABLE favorites (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    church_id bigint NOT NULL REFERENCES churches(id),
    user_id bigint NOT NULL REFERENCES users(id),
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT uq_favorites_church_user UNIQUE (church_id, user_id)
);

-- FavoriteService.listMyFavorites queries by user_id (church_id already has an implicit
-- index via its own PK/unique constraint lookups, but user_id doesn't).
CREATE INDEX idx_favorites_user_id ON favorites (user_id);
