-- "Recently viewed churches" (project-owner request, 2026-09-22) — feeds the
-- Favorites page's empty state (recently viewed + suggestions) instead of a bare
-- "no favorites yet". One row per (church, user): repeat visits update viewed_at
-- rather than growing an unbounded log, since all this ever needs is "the last time
-- you looked at each church you've looked at" — not a full visit history.
-- Anonymous (logged-out) visits are never recorded — there's no user to attach them
-- to, and no Favorites page for them to seed anyway.
CREATE TABLE church_views (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    church_id bigint NOT NULL REFERENCES churches(id),
    user_id bigint NOT NULL REFERENCES users(id),
    viewed_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT uq_church_views_church_user UNIQUE (church_id, user_id)
);

-- FavoriteService reads "my most recent views" ordered by viewed_at.
CREATE INDEX idx_church_views_user_viewed_at ON church_views (user_id, viewed_at DESC);
