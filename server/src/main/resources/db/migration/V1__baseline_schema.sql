-- Baseline schema, reproducing exactly what Hibernate's ddl-auto=update had already
-- created for the current entity set (dumped via pg_dump --schema-only against a
-- scratch database running today's code, then cleaned up — see docs/ARCHITECTURE.md
-- "Database"). From here on, schema changes are Flyway migrations, not Hibernate DDL.

CREATE TABLE churches (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name character varying(255) NOT NULL,
    denomination character varying(255),
    address character varying(255),
    city character varying(255),
    state character varying(255),
    zip_code character varying(255),
    phone character varying(255),
    email character varying(255),
    website character varying(255),
    description text,
    image_url character varying(255),
    pastor character varying(255),
    facebook character varying(255),
    instagram character varying(255),
    youtube character varying(255),
    claimed boolean NOT NULL,
    latitude double precision,
    longitude double precision
);

CREATE TABLE service_times (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    church_id bigint NOT NULL REFERENCES churches(id),
    day_of_week character varying(255),
    "time" character varying(255),
    type character varying(255),
    language character varying(255)
);

CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email character varying(255) NOT NULL,
    password_hash character varying(255) NOT NULL,
    role character varying(255) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT users_role_check CHECK (role IN ('MEMBER', 'VOLUNTEER', 'CHURCH_ADMIN', 'PLATFORM_ADMIN'))
);

CREATE TABLE volunteer_invites (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code character varying(255) NOT NULL,
    status character varying(255) NOT NULL,
    created_by_id bigint NOT NULL REFERENCES users(id),
    redeemed_by_id bigint REFERENCES users(id),
    created_at timestamp(6) with time zone NOT NULL,
    expires_at timestamp(6) with time zone,
    redeemed_at timestamp(6) with time zone,
    CONSTRAINT uq_volunteer_invites_code UNIQUE (code),
    CONSTRAINT volunteer_invites_status_check CHECK (status IN ('PENDING', 'REDEEMED', 'REVOKED'))
);

CREATE TABLE claims (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    church_id bigint NOT NULL REFERENCES churches(id),
    user_id bigint NOT NULL REFERENCES users(id),
    status character varying(255) NOT NULL,
    notes text,
    decided_by_id bigint REFERENCES users(id),
    created_at timestamp(6) with time zone NOT NULL,
    decided_at timestamp(6) with time zone,
    CONSTRAINT claims_status_check CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED'))
);

CREATE TABLE church_staff (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    church_id bigint NOT NULL REFERENCES churches(id),
    user_id bigint NOT NULL REFERENCES users(id),
    is_owner boolean NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT uq_church_staff_church_user UNIQUE (church_id, user_id)
);

CREATE TABLE church_staff_permissions (
    church_staff_id bigint NOT NULL REFERENCES church_staff(id),
    permission character varying(255),
    CONSTRAINT church_staff_permissions_permission_check
        CHECK (permission IN ('EDIT_PROFILE', 'MANAGE_SERMONS', 'MANAGE_EVENTS', 'MANAGE_STAFF'))
);

CREATE TABLE church_submissions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_church_id bigint REFERENCES churches(id),
    payload text NOT NULL,
    submitted_by character varying(255) NOT NULL,
    status character varying(255) NOT NULL,
    reviewed_by_id bigint REFERENCES users(id),
    created_at timestamp(6) with time zone NOT NULL,
    reviewed_at timestamp(6) with time zone,
    CONSTRAINT church_submissions_status_check CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED'))
);

CREATE TABLE church_images (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    church_id bigint NOT NULL REFERENCES churches(id),
    url character varying(255) NOT NULL,
    sort_order integer NOT NULL
);

CREATE TABLE events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title character varying(255) NOT NULL,
    description text,
    starts_at timestamp(6) with time zone NOT NULL,
    ends_at timestamp(6) with time zone
);

-- Co-hosting churches for an event; see Event.churches's @JoinTable.
CREATE TABLE event_churches (
    event_id bigint NOT NULL REFERENCES events(id),
    church_id bigint NOT NULL REFERENCES churches(id),
    PRIMARY KEY (event_id, church_id)
);

CREATE TABLE sermons (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    church_id bigint NOT NULL REFERENCES churches(id),
    title character varying(255) NOT NULL,
    date date NOT NULL,
    media_url character varying(255)
);
