-- 1:1 direct messages between users (project-owner audit, 2026-09-22) — separate from
-- `messages` (the per-church group chat, V6): a DM has no church at all, just two
-- users. read_at (nullable) powers unread badges on the conversation list; group chat
-- has no equivalent since there's no per-recipient row to mark.
CREATE TABLE direct_messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id bigint NOT NULL REFERENCES users(id),
    recipient_id bigint NOT NULL REFERENCES users(id),
    body TEXT NOT NULL,
    sent_at timestamp(6) with time zone NOT NULL,
    read_at timestamp(6) with time zone,
    CONSTRAINT chk_direct_messages_not_self CHECK (sender_id <> recipient_id)
);

-- DirectMessageRepository.findConversation reads "either direction between these two
-- users" — both orderings get their own index rather than relying on one being scanned
-- backwards, and both carry sent_at so the ORDER BY in that query stays index-only.
CREATE INDEX idx_direct_messages_sender_recipient ON direct_messages (sender_id, recipient_id, sent_at);
CREATE INDEX idx_direct_messages_recipient_sender ON direct_messages (recipient_id, sender_id, sent_at);
