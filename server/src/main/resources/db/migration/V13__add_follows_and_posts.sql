-- The "church social media" angle (project-owner request, 2026-09-22): users follow a
-- church (distinct from Favorite, which is a private bookmark with no feed
-- implications, and from Member, which is congregational — see docs/DATA_MODEL.md) and
-- see a chronological feed of that church's posts.
CREATE TABLE follows (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    church_id bigint NOT NULL REFERENCES churches(id),
    user_id bigint NOT NULL REFERENCES users(id),
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT uq_follows_church_user UNIQUE (church_id, user_id)
);

CREATE INDEX idx_follows_user_id ON follows (user_id);
-- PostService.requireFollowerOrManager and the "who follows this church" question
-- both key off church_id.
CREATE INDEX idx_follows_church_id ON follows (church_id);

CREATE TABLE posts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    church_id bigint NOT NULL REFERENCES churches(id),
    author_id bigint NOT NULL REFERENCES users(id),
    body text NOT NULL,
    -- Not wired up to an upload flow in this pass (text-only posts for now) — the
    -- column exists so that's a follow-up, not another migration, once it lands.
    image_url character varying(1024),
    created_at timestamp(6) with time zone NOT NULL
);

-- Both PostRepository queries — a church's own post list, and the followed-church
-- feed (a join against follows) — page backwards by (church_id, id) / id, newest first.
CREATE INDEX idx_posts_church_id_id ON posts (church_id, id DESC);

-- New ChurchPermission.MANAGE_POSTS — church_staff_permissions has a CHECK constraint
-- enumerating every valid value (V1__baseline_schema.sql), which must be widened or
-- ChurchStaffService.grantOwnership (which grants every ChurchPermission.values() to a
-- new owner) would start failing its INSERT the moment this enum constant exists.
ALTER TABLE church_staff_permissions DROP CONSTRAINT church_staff_permissions_permission_check;
ALTER TABLE church_staff_permissions ADD CONSTRAINT church_staff_permissions_permission_check
    CHECK (permission IN ('EDIT_PROFILE', 'MANAGE_SERMONS', 'MANAGE_EVENTS', 'MANAGE_STAFF', 'MANAGE_POSTS'));
