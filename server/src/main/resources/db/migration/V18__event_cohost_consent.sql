-- Co-host consent (found in review, 2026-09-23): an event organizer only ever needed
-- MANAGE_EVENTS on ONE of an event's churches to associate ANY other church as a
-- "co-host" — a church could be presented as sponsoring an event it never agreed to.
-- Replaces the plain event_churches join table with one that carries a status: a
-- church the organizer can actually manage is CONFIRMED immediately; any other named
-- church is PENDING until one of ITS OWN MANAGE_EVENTS staff accepts or declines
-- (EventService.respondToCoHost). Public displays (EventDto.churches) only ever show
-- CONFIRMED co-hosts.
CREATE TABLE event_co_hosts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id bigint NOT NULL REFERENCES events(id),
    church_id bigint NOT NULL REFERENCES churches(id),
    status character varying(20) NOT NULL DEFAULT 'CONFIRMED',
    invited_by_id bigint REFERENCES users(id),
    created_at timestamp(6) with time zone NOT NULL DEFAULT now(),
    responded_at timestamp(6) with time zone,
    CONSTRAINT uq_event_co_hosts_event_church UNIQUE (event_id, church_id),
    CONSTRAINT event_co_hosts_status_check CHECK (status IN ('CONFIRMED', 'PENDING', 'DECLINED'))
);

-- Existing co-host rows predate the consent requirement entirely — backfilled as
-- CONFIRMED (not reset to PENDING) so already-published events don't suddenly lose
-- their listed co-hosts.
INSERT INTO event_co_hosts (event_id, church_id, status, created_at)
SELECT event_id, church_id, 'CONFIRMED', now() FROM event_churches;

DROP TABLE event_churches;

CREATE INDEX idx_event_co_hosts_event_id ON event_co_hosts (event_id);
-- EventService.myPendingCoHostInvitations reads "PENDING rows for churches I manage".
CREATE INDEX idx_event_co_hosts_church_id_status ON event_co_hosts (church_id, status);
