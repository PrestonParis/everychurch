-- Prompt 14 (docs/PROMPTS.md): per-church group chat. One channel per church — the
-- church_id IS the channel, so there's no separate channel table.

CREATE TABLE messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    church_id bigint NOT NULL REFERENCES churches(id),
    sender_id bigint NOT NULL REFERENCES users(id),
    body text NOT NULL,
    sent_at timestamp(6) with time zone NOT NULL
);

-- History paging walks a church's messages newest-first by id (a cursor), so this
-- composite index serves both "latest N" and "N before id X" without a sort.
CREATE INDEX idx_messages_church_id_id ON messages (church_id, id DESC);
