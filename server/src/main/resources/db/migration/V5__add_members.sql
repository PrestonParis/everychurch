-- Prompt 13 (docs/PROMPTS.md): plain congregational membership, distinct from church_staff.
-- The prerequisite for the per-church group chat (Prompt 14).

CREATE TABLE members (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    church_id bigint NOT NULL REFERENCES churches(id),
    user_id bigint NOT NULL REFERENCES users(id),
    joined_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT uq_members_church_user UNIQUE (church_id, user_id)
);

CREATE INDEX idx_members_user_id ON members (user_id);
