-- Moderation primitives (project-owner request, 2026-09-23): DM blocking, and a
-- generic report a Platform Admin can review. Both were flagged as outstanding
-- "product work" in the Prompt 16 findings (docs/PROMPTS.md) and by a later review
-- (docs/ARCHITECTURE.md "Known limitations" under Chat) — this is that work landing.
CREATE TABLE blocks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blocker_id bigint NOT NULL REFERENCES users(id),
    blocked_id bigint NOT NULL REFERENCES users(id),
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT uq_blocks_blocker_blocked UNIQUE (blocker_id, blocked_id),
    CONSTRAINT chk_blocks_not_self CHECK (blocker_id <> blocked_id)
);

-- DirectMessageService checks "does either direction have a block row" on every send.
CREATE INDEX idx_blocks_blocker_blocked ON blocks (blocker_id, blocked_id);
CREATE INDEX idx_blocks_blocked_blocker ON blocks (blocked_id, blocker_id);

-- Matches the shape docs/DATA_MODEL.md already specced for this planned entity
-- (targetType USER/CHURCH, status OPEN/ACTIONED/DISMISSED) — implemented here rather
-- than redesigned.
CREATE TABLE reports (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id bigint NOT NULL REFERENCES users(id),
    target_type character varying(20) NOT NULL,
    target_id bigint NOT NULL,
    reason text NOT NULL,
    status character varying(20) NOT NULL DEFAULT 'OPEN',
    created_at timestamp(6) with time zone NOT NULL,
    resolved_at timestamp(6) with time zone,
    resolved_by_id bigint REFERENCES users(id),
    CONSTRAINT chk_reports_target_type CHECK (target_type IN ('USER', 'CHURCH')),
    CONSTRAINT chk_reports_status CHECK (status IN ('OPEN', 'ACTIONED', 'DISMISSED'))
);

-- AdminReportController lists open reports first, newest first.
CREATE INDEX idx_reports_status_created_at ON reports (status, created_at DESC);
